def main():
    existing = []
    if os.path.exists(SRC):
        with open(SRC, encoding="utf-8") as f:
            existing = json.load(f)

    seen = set()
    merged = []
    for e in existing:
        ru = (e.get("ru") or "").strip()
        if not ru:
            continue
        key = ru.lower()
        if key in seen:
            continue
        seen.add(key)
        merged.append({"ru": ru, "zh": (e.get("zh") or "").strip(),
                       "audio": e.get("audio") or audio_url(ru)})

    added = 0
    for ru, zh in CURATED + EXTRA:
        ru = ru.strip()
        if not ru:
            continue
        key = ru.lower()
        if key in seen:
            continue
        seen.add(key)
        merged.append({"ru": ru, "zh": zh.strip(), "audio": audio_url(ru)})
        added += 1

    # 排序：保持现有在前，新词在后（不强制字母序，便于教材连贯）
    json.dump(merged, open(SRC, "w", encoding="utf-8"),
              ensure_ascii=False, indent=2)
    if os.path.exists(IMPORT):
        json.dump(merged, open(IMPORT, "w", encoding="utf-8"),
                  ensure_ascii=False, indent=2)

    print("现有保留: %d，新增: %d，总计: %d" % (len(existing) - (len(existing) - sum(1 for e in existing if (e.get('ru') or '').strip())), added, len(merged)))
    print("已写入: %s 和 %s" % (SRC, IMPORT))
    # 抽查
    for e in merged[:3] + merged[-3:]:
        print("  %-18s %-14s" % (e["ru"], e["zh"][:14]))


if __name__ == "__main__":
    main()
