/** 字母读音 assets 路径（按字母表顺序编号，已离线内嵌到 App）。 */
fun letterAsset(l: LetterInfo): String =
    "audio/letters/letter_%02d.mp3".format(CYRILLIC_ALPHABET.indexOfFirst { it.upper == l.upper }.coerceAtLeast(0))

/** 例词读音 assets 路径。 */
fun wordAsset(l: LetterInfo): String =
    "audio/letters/word_%02d.mp3".format(CYRILLIC_ALPHABET.indexOfFirst { it.upper == l.upper }.coerceAtLeast(0))

